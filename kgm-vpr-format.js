const MASK_PATH = path.join(__dirname, "public", "assets", "kgm.mask");

let cachedMask = null;

function formatError(message, code) {
  const error = new Error(message);
  error.code = code;
  return error;
}


function transformNibble(byte) {
  return (byte ^ ((byte & 0x0f) << 4)) & 0xff;
}

function decryptVprBuffer(fileBuffer, maskV2) {
  if (!Buffer.isBuffer(fileBuffer) || fileBuffer.length < 0x2c) {
    throw formatError("VPR 文件不完整。", "VPR_INVALID_FILE");
  }
  if (!fileBuffer.subarray(0, VPR_HEADER.length).equals(VPR_HEADER)) {
    throw formatError("不是合法的 VPR 加密音频文件。", "VPR_INVALID_FILE");
  }
  const headerLength = fileBuffer.readUInt32LE(0x10);
  if (headerLength < 0x2c || headerLength > fileBuffer.length) {
    throw formatError("VPR 文件头长度无效。", "VPR_INVALID_FILE");
  }
  const audio = Buffer.from(fileBuffer.subarray(headerLength));
  const requiredMaskBytes = Math.ceil(audio.length / 16);
  if (!Buffer.isBuffer(maskV2) || maskV2.length < requiredMaskBytes) {
    throw formatError(
      `VPR 音频数据超出当前解密掩码覆盖范围（最多 ${Math.floor((maskV2?.length || 0) * 16 / 1024 / 1024)} MiB）。`,
      "VPR_MASK_RANGE_EXCEEDED"
    );
  }
  const key = Buffer.alloc(17);
  fileBuffer.copy(key, 0, 0x1c, 0x2c);
  for (let i = 0; i < audio.length; i += 1) {
    const keyed = transformNibble(key[i % 17] ^ audio[i]);
    const mask = transformNibble(MASK_V2_PREDEF[i % MASK_V2_PREDEF.length] ^ maskV2[i >> 4]);
    audio[i] = keyed ^ mask ^ VPR_MASK_DIFF[i % VPR_MASK_DIFF.length];
  }
  return audio;
}

async function loadMask() {
  if (!cachedMask) cachedMask = await fsp.readFile(MASK_PATH);
  return cachedMask;
}

async function convertVpr(inputPath) {
  const [fileBuffer, maskV2] = await Promise.all([fsp.readFile(inputPath), loadMask()]);
  const audio = decryptVprBuffer(fileBuffer, maskV2);
  const format = detectAudioFormat(audio);
  if (format === "unknown") {
    throw formatError("VPR 解密结果不是可识别的音频格式。", "VPR_DECRYPT_FAILED");
  }
  const tempDir = await fsp.mkdtemp(path.join(os.tmpdir(), "mahiro-vpr-"));
  const nativePath = path.join(tempDir, `native.${format}`);
  await fsp.writeFile(nativePath, audio);
  return { nativePath, format, tempDir };
}

